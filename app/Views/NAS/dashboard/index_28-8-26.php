    <script id="nas-dashboard-mobile-ux-script">
    /*
    |--------------------------------------------------------------------------
    | SMALL DEVICE VISUAL BEHAVIOR ONLY
    |--------------------------------------------------------------------------
    | Reuses existing elements. No API calls, IDs, routes, upload, sync,
    | preview, sharing, or cluster logic is replaced.
    */
    (function () {
        'use strict';

        const mobileQuery = window.matchMedia('(max-width: 768px)');
        const sidebar = document.getElementById('sidebar');
        const menuToggle = document.getElementById('menuToggle');
        const storageInfo = sidebar ? sidebar.querySelector('.storage-info') : null;
        const syncBody = document.getElementById('syncBody');
        const unsyncedSection = document.getElementById('syncUnsyncedSection');

        if (!sidebar || !menuToggle) {
            return;
        }

        const storageAnchor = storageInfo
            ? document.createComment('nas-storage-original-position')
            : null;

        if (storageInfo && storageAnchor) {
            storageInfo.parentNode.insertBefore(storageAnchor, storageInfo);
        }

        const backdrop = document.createElement('div');
        backdrop.className = 'nas-mobile-nav-backdrop';
        backdrop.setAttribute('aria-hidden', 'true');
        document.body.appendChild(backdrop);

        function moveStorageForViewport() {
            if (!storageInfo) {
                return;
            }

            const syncSection = document.getElementById('syncSection');

            if (!syncSection || !syncSection.parentNode) {
                return;
            }

            /* Keep the same Storage element/IDs directly below
               Synchronization on every viewport size. */
            if (storageInfo.previousElementSibling !== syncSection) {
                syncSection.parentNode.insertBefore(
                    storageInfo,
                    syncSection.nextSibling
                );
            }
        }

        function setMobileMenu(open) {
            if (!mobileQuery.matches) {
                document.body.classList.remove('nas-mobile-nav-open');
                menuToggle.setAttribute('aria-expanded', 'false');
                return;
            }

            document.body.classList.toggle('nas-mobile-nav-open', open);
            menuToggle.setAttribute('aria-expanded', open ? 'true' : 'false');
        }

        menuToggle.setAttribute('aria-expanded', 'false');

        menuToggle.addEventListener('click', function () {
            if (!mobileQuery.matches) {
                return;
            }

            setMobileMenu(
                !document.body.classList.contains('nas-mobile-nav-open')
            );
        });

        backdrop.addEventListener('click', function () {
            setMobileMenu(false);
        });

        sidebar.addEventListener('click', function (event) {
            if (!mobileQuery.matches) {
                return;
            }

            if (event.target.closest('#clusterNav li')) {
                setMobileMenu(false);
            }
        });

        document.addEventListener('keydown', function (event) {
            if (event.key === 'Escape' && mobileQuery.matches) {
                setMobileMenu(false);
            }
        });

        function handleViewportChange() {
            moveStorageForViewport();

            if (!mobileQuery.matches) {
                setMobileMenu(false);
            }
        }

        if (typeof mobileQuery.addEventListener === 'function') {
            mobileQuery.addEventListener('change', handleViewportChange);
        } else if (typeof mobileQuery.addListener === 'function') {
            mobileQuery.addListener(handleViewportChange);
        }

        moveStorageForViewport();
    })();
    </script>


