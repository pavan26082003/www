    <script id="nas-dashboard-theme-script">
    (function () {
        'use strict';

        const storageKey = 'efactor_nas_home_theme';
        const root = document.documentElement;
        const toggle = document.getElementById('nasThemeToggle');

        if (!toggle) {
            return;
        }

        function currentTheme() {
            return root.getAttribute('data-nas-theme') === 'dark'
                ? 'dark'
                : 'light';
        }

        function renderThemeButton() {
            const dark = currentTheme() === 'dark';
            const icon = toggle.querySelector('i');

            toggle.title = dark
                ? 'Switch to light theme'
                : 'Switch to dark theme';

            toggle.setAttribute(
                'aria-label',
                dark
                    ? 'Switch to light theme'
                    : 'Switch to dark theme'
            );

            if (icon) {
                icon.className = dark
                    ? 'fas fa-sun'
                    : 'fas fa-moon';
            }
        }

        function setTheme(theme) {
            const safeTheme = theme === 'dark' ? 'dark' : 'light';

            root.setAttribute('data-nas-theme', safeTheme);

            try {
                localStorage.setItem(storageKey, safeTheme);
            } catch (error) {
                console.warn('Unable to save NAS theme preference:', error);
            }

            renderThemeButton();
        }

        toggle.addEventListener('click', function () {
            setTheme(
                currentTheme() === 'dark'
                    ? 'light'
                    : 'dark'
            );
        });

        renderThemeButton();
    })();
    </script>


